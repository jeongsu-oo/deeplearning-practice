#  이 파일은 문제 파일의 "4단계: 그래도 안 되면 정답 파일을 여세요" 에 해당합니다.
#  A, B 는 이미 문제 파일에 채워져 있었으므로 그대로 두고, C·D·E 와 자체점검의
#  숨은 함정(손실 별칭) 만 설명합니다. 각 섹션은 (1) 정답 코드 (2) 왜 이렇게 되는지 순서로 적었습니다.
#  실행하면 미니실습01_문제.py 와 똑같은 숫자가 나오는 걸 직접 확인해 보세요.
# =====================================================================

import os
import numpy as np
import pandas as pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "데이터")
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")
x = df["공기온도"].values.astype(float)
y = df["공정온도"].values.astype(float)


# ---------------------------------------------------------------------
# A, B — 문제 파일 그대로 (이미 풀려 있던 부분)
# ---------------------------------------------------------------------
def pred(x, w, b):
    return w * x + b


def mse(x, y, w, b):
    err = y - pred(w, x, b)
    return np.mean(err**2)


h = 0.0001


def grad(x, y, w, b):
    gw = (mse(x, y, w + h, b) - mse(x, y, w - h, b)) / (2 * h)
    gb = (mse(x, y, w, b + h) - mse(x, y, w, b - h)) / (2 * h)
    return gw, gb


# ★ B의 "생각할 것" 답 ★
#   gw(-580.548)가 gb(-1.934)보다 왜 300배쯤 클까?
#   pred(x,w,b) = w*x + b 이기 때문입니다.
#     - w 를 h 만큼 키우면 예측값은 h*x 만큼 변합니다. x(공기온도)가 300 근처 값이라,
#       w 를 살짝만 건드려도 예측값은 그만큼(≈300배) 증폭되어 흔들립니다.
#     - b 를 h 만큼 키우면 예측값은 그냥 h 만큼만 변합니다. x 가 얼마든 상관없이 항상 같은 크기.
#   기울기는 "이 손잡이를 건드렸을 때 손실이 얼마나 흔들리나"를 재는 것이므로,
#   w 손잡이는 매번 x(≈300) 배로 증폭되어 흔들리고 b 손잡이는 증폭 없이 그대로 흔들립니다.
#   → 이 300배 차이가 다음 [C]에서 사고를 칩니다: w 와 b 에 똑같은 보폭(lr)을 곱하면
#     이미 300배 큰 gw 에 그 보폭이 곱해지니 w 쪽이 한 걸음에 훨씬 크게 움직여 튕겨나갑니다.


# ★ 자체점검 함정 하나 미리 알려드립니다 ★
# 맨 아래 [자체 점검]의 "학습" 항목은 이렇게 되어 있습니다:
#     "손실(x, y, w_gd, b_gd) < 0.9"
# 앞의 세 항목(예측/손실/기울기)은 pred, mse, grad 라는 영어 이름을 그대로 부르는데,
# 이 항목만 "손실" 이라는 한글 이름을 함수처럼 호출합니다.
# 즉 mse 를 아무리 완벽히 만들어도, 이름이 "손실" 이 아니면 NameError 가 나서
# 학습을 제대로 했어도 "[ ] 학습 — 아직 안 만들었습니다" 로 뜹니다.
# 해결: mse 를 새로 하나 더 만들 필요 없이, 같은 함수를 가리키는 별명을 하나 만들어 두면 됩니다.
손실 = mse
#   ↑ 이 줄 하나로 "손실" 이라는 이름도 mse 와 똑같은 함수를 가리키게 됩니다.
#   파이썬에서 함수 이름도 그냥 변수라서, 다른 이름에 대입하면 별명이 생깁니다.


# =====================================================================
# C. 일부러 실패시키기 — 발산                                     (01 §5)
# =====================================================================
# [무엇을 하는가]
#   w=1.0, b=9.0 에서 시작해서, "새 값 = 지금 값 − 보폭 × 기울기" 라는 한 걸음 규칙을
#   20번 반복합니다. 보폭(lr)은 0.001 이지만, x 가 200~300대 스케일의 큰 숫자라서
#   기울기(특히 gw)도 이미 -580 처럼 큰 값이었죠(B에서 확인함).
#   "보폭 × 기울기" 가 크면 한 걸음에 너무 멀리 가버리고, 거기서 잰 기울기는
#   원래보다 훨씬 더 크므로 다음 걸음은 더 멀리 튕깁니다. 이게 눈덩이처럼 불어나는 게 발산입니다.
with np.errstate(over="ignore", invalid="ignore"):
    w_c, b_c = 1.0, 9.0
    lr_c = 0.001
    for _ in range(20):
        gw_c, gb_c = grad(x, y, w_c, b_c)
        w_c = w_c - lr_c * gw_c
        b_c = b_c - lr_c * gb_c
    print(f"[C] 20걸음 뒤 손실 = {mse(x, y, w_c, b_c):.4e}")
# 나와야 하는 값: 3.7917e+31  (직접 돌려서 검증 완료)
#
# [왜 이런 코드가 되는가]
#   - w_c, b_c 를 매 걸음 "동시에" 갱신해야 합니다. gw_c, gb_c 를 먼저 둘 다 구해 놓고
#     (같은 시점의 w_c, b_c 기준으로) 나중에 두 값을 같이 바꾸는 순서가 중요합니다.
#     만약 w_c 를 먼저 바꾼 뒤 그 새 w_c 로 gb_c 를 구하면 살짝 다른(비표준) 계산이 됩니다.
#   - with np.errstate(...) 는 "계산은 그대로 하되 경고 메시지만 끄는" 용도입니다.
#     실제로 오버플로가 나서 값이 inf 나 매우 큰 수가 되는 건 막지 않습니다 — 오히려 그게 이 실습의 목적.
#   - .4e 는 지수 표기(예: 3.7917e+31)로 찍으라 는 뜻으로, f"{값:.4e}" 형태로 씁니다.


# =====================================================================
# D. 눈금을 바꿔서 해결 — 표준화                              (01 §5, §6)
# =====================================================================
# [왜 표준화를 하면 발산이 안 멎는가]
#   C에서 발산한 근본 원인은 "x 가 300 근처의 큰 수라서 gw 가 gb 보다 300배쯤 컸다"는 것(B의 생각할 것).
#   기울기 크기가 방향마다 너무 다르면, 모든 방향에 똑같은 보폭(lr)을 곱하는 경사하강법은
#   한쪽(w)에는 적당한 보폭이 다른 쪽(b)에는 아무 의미 없이 작거나, 반대로 w 쪽엔 너무 커서 튕깁니다.
#   x 를 표준화해서 평균 0, 표준편차 1 짜리 "얌전한" 숫자로 바꾸면, w 방향 기울기도 더 이상
#   비정상적으로 크지 않아져서 하나의 lr 로 두 방향 모두 안정적으로 내려갈 수 있습니다.
m = x.mean()
s = x.std()
z = (x - m) / s
# 확인: z.mean() ≈ 0, z.std() ≈ 1  (자체점검 "표준화" 항목이 이걸 확인합니다)


def 학습(z, y, w0, b0, lr, epochs):
    w, b = w0, b0
    for _ in range(epochs):
        gw, gb = grad(z, y, w, b)
        w = w - lr * gw
        b = b - lr * gb
    return w, b


# w=0, b=0 에서 시작해서 lr=0.1 로 300걸음
w_z, b_z = 학습(z, y, 0.0, 0.0, 0.1, 300)

# [원래 눈금으로 되돌리기 — 왜 이 식인가]
#   z-눈금 위에서 찾은 직선은  y = w_z * z + b_z  입니다.
#   그런데 z = (x - m) / s 이므로, 이걸 그대로 대입하면
#       y = w_z * (x - m) / s + b_z
#         = (w_z / s) * x + (b_z - w_z * m / s)
#   즉 원래 x 눈금에서의 기울기는 w_z/s, 절편은 b_z - w_z*m/s 입니다.
#   "외울 식"이 아니라 그냥 z 의 정의를 대입해서 x 에 대해 다시 정리한 것뿐입니다.
w_gd = w_z / s
b_gd = b_z - w_z * m / s

print(f"[D] 평균 {m:.2f}  표준편차 {s:.2f}")
print(f"[D] 공정온도 = {w_gd:.4f} x 공기온도 + {b_gd:.4f}")
print(f"[D] 손실 = {mse(x, y, w_gd, b_gd):.4f}")
# 나와야 하는 값: 평균 300.24, 표준편차 1.91, 0.9840x+14.7799, 손실 0.8921 (직접 돌려서 검증 완료)


# =====================================================================
# E. 보폭은 얼마가 맞나                                           (01 §7)
# =====================================================================
for lr in [0.001, 0.1, 1.05]:
    w_e, b_e = 학습(z, y, 0.0, 0.0, lr, 300)
    with np.errstate(over="ignore", invalid="ignore"):
        w_gd_e = w_e / s
        b_gd_e = b_e - w_e * m / s
        loss_e = mse(x, y, w_gd_e, b_gd_e)

    # [판정 규칙 — 왜 np.isnan 을 먼저 봐야 하는가]
    #   lr=1.05 처럼 심하게 발산하면 값이 inf 를 넘어 "정의할 수 없는 계산"(inf - inf 등)이 튀어나와
    #   nan(Not a Number)이 됩니다. nan 은 자기 자신과 비교해도 False 가 나오는 특수한 값이라
    #   "loss_e > 1e6" 같은 크기 비교로는 절대 걸러지지 않습니다(nan > 1e6 은 그냥 False).
    #   그래서 np.isnan 으로 "숫자가 아님" 자체를 먼저 확인해야 발산을 놓치지 않습니다.
    if np.isnan(loss_e) or loss_e > 1e6:
        판정 = "발산"
    elif loss_e > 1.0:
        판정 = "굼벵이"
    else:
        판정 = "좋음"

    print(f"[E] lr={lr:<5} -> 손실 {loss_e:>20.4f}   {판정}")
# 나와야 하는 값:
#   lr=0.001 -> 28950.6776  굼벵이
#   lr=0.1   -> 0.8921      좋음
#   lr=1.05  -> 약 2.289e+22 발산   (직접 돌려서 검증 완료)
#
# [생각할 것 답]
#   lr=0.001 이 "틀린" 게 아니라 "굼벵이"인 이유:
#     이 보폭은 골짜기 반대편으로 튕길 만큼 크지도, 계산이 깨질 만큼 이상하지도 않습니다.
#     그저 한 걸음의 폭이 너무 좁아서, 300걸음 만에 바닥(최적점) 근처에 도착하지 못했을 뿐입니다.
#     방향은 맞게 가고 있으므로 "틀렸다"가 아니라 "느리다"가 맞는 진단입니다.
#   30000걸음이면 어떻게 되는가:
#     같은 방향으로 계속 내려가므로, 시간(걸음 수)만 충분히 주면 결국 lr=0.1 때와 비슷한
#     바닥(손실 ≈ 0.89 근처)까지 내려갑니다. 다만 실전에서는 걸음마다 계산 비용이 들기 때문에
#     "느린 lr + 아주 많은 걸음" 보다는 "적당한 lr(여기선 0.1 근처)" 이 훨씬 효율적입니다.


