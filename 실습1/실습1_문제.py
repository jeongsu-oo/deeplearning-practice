# B7. 경사하강 함수를 만드세요. 이름은 경사하강(lr=0.1, epochs=300) 으로 하고,
#     w 와 b 를 돌려주게 하세요.
#       w, b 를 0 에서 출발
#       epochs 번 반복
#       한 걸음 = 기울기를 구하고, 손잡이 = 손잡이 - lr * 기울기
#
#     300걸음 뒤의 w, b 와 손실을 출력하세요.
#
# [나와야 하는 출력]
#     300걸음 후  w = 3.8643 / b = 12.745
#     손실: 6.6555
#
#     (B4 의 38.7788 에서 6.6555 까지 내려왔습니다. 6분의 1 입니다)
#
#     주의: w 와 b 의 기울기를 '둘 다 구한 다음에' 갱신해야 합니다.
#          w 를 먼저 바꾸고 b 의 기울기를 구하면 틀립니다.
#          답이 비슷하게 나와서 틀린 걸 못 알아채기 쉬우니 순서를 확인하세요.
# ---------------------------------------------------------------------


# TODO: 여기에 코드를 쓰세요
def 경사하강(lr=0.1, epochs=300):
    w, b = 0, 0
    h = 0.0001
    for i in range(epochs):
        grad_w = (L(w + h, b) - L(w - h, b)) / (2 * h)
        grad_b = (L(w, b + h) - L(w, b - h)) / (2 * h)

        w = w - lr * grad_w
        b = b - lr * grad_b

    return w, b


f_w, f_b = 경사하강()
f_loss = L(f_w, f_b)
print("w = ", f_w.round(4), "b =", f_b.round(4))
print(f_loss.round(4))

